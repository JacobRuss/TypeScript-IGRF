import { calculateField } from '../math/field';
import { geodeticToSpherical } from '../math/coordinates';

// Эталон: ppigrf 2.1.0 (IGRF-14), геоцентрические компоненты, значения посчитаны внешним скриптом
// X на север, Y на восток, Z вниз, нТл
describe('Сверка с ppigrf (IGRF-14)', () => {
  // [lat, lon, h_km, year, X, Y, Z, F]
  const REFERENCE: Array<[number, number, number, number, number, number, number, number]> = [
    [90.0, 0.0, 0.0, 2020, 1816.713, 126.559, 56727.876, 56757.100],
    [-90.0, 0.0, 0.0, 2020, 14430.892, -8568.327, -52025.281, 54665.316],
    [89.5, 120.0, 0.0, 2025, -1136.275, 1202.136, 56942.492, 56966.513],
    [0.0, 0.0, 0.0, 2025, 27456.622, -1926.549, -15997.353, 31835.404],
    [0.0, 90.0, 0.0, 2000, 39485.584, -1704.781, -14651.325, 42150.669],
    [0.0, -75.0, 0.0, 2010, 27105.383, -2245.875, 11076.231, 29367.135],
    [55.75, 37.62, 0.0, 2020, 16193.850, 3301.157, 50042.511, 52700.961],
    [-25.0, -45.0, 300.0, 2020, 14579.195, -5333.514, -13176.124, 20361.963],
    [-33.87, 151.21, 0.0, 1980, 24138.583, 5253.142, -52357.378, 57892.674],
    [60.0, 0.0, 0.0, 1950, 14222.808, -2703.101, 46948.016, 49129.535],
    [45.0, -100.0, 0.0, 1900, 17224.271, 4049.034, 60042.151, 62594.969],
    [35.68, 139.69, 400.0, 2030, 24852.802, -2908.568, 29616.181, 38771.636],
  ];

  it.each(REFERENCE)('lat=%f lon=%f h=%f год=%i', (lat, lon, h, year, X, Y, Z, F) => {
    const { theta, phi, r } = geodeticToSpherical(lat, lon, h);
    const result = calculateField(theta, phi, r, year);
    expect(result.X).toBeCloseTo(X, 2);
    expect(result.Y).toBeCloseTo(Y, 2);
    expect(result.Z).toBeCloseTo(Z, 2);
    expect(result.F).toBeCloseTo(F, 2);
  });
});